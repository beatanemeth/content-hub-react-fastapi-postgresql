-- Columns follow the CSV header order, so COPY ... HEADER MATCH in 02-seed.sql can check them.
-- BY DEFAULT (not ALWAYS) lets COPY write the ids that are already in the CSV files.

-- Parent tables: no foreign keys.

-- full_name is UNIQUE, so the author dropdown never shows two people with the same name.
CREATE TABLE person (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	full_name text NOT NULL UNIQUE,
	email text NOT NULL UNIQUE,
	occupation text NOT NULL
);

CREATE TABLE venue (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name text NOT NULL,
	address text NOT NULL
);

CREATE TABLE category (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	label text NOT NULL UNIQUE
);

CREATE TABLE event_category (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	label text NOT NULL UNIQUE
);

CREATE TABLE tag (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	label text NOT NULL UNIQUE
);

-- Roles of a person: one row per person at most, so person_id is the primary key.

CREATE TABLE staff (
	person_id integer PRIMARY KEY REFERENCES person (id),
	job_title text NOT NULL,
	phone text NOT NULL,
	joined_on date NOT NULL
);

CREATE TABLE founder (
	person_id integer PRIMARY KEY REFERENCES person (id),
	bio text NOT NULL
);

-- Posts and their link tables.

CREATE TABLE post (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	title text NOT NULL,
	summary text NOT NULL,
	body text NOT NULL,
	author_id integer NOT NULL REFERENCES person (id),
	published_on date NOT NULL,
	updated_at timestamptz NOT NULL
);

-- ON DELETE CASCADE: deleting a post also deletes its link rows, instead of being blocked by them.
CREATE TABLE post_category (
	post_id integer REFERENCES post (id) ON DELETE CASCADE,
	category_id integer REFERENCES category (id),
	PRIMARY KEY (post_id, category_id)
);

CREATE TABLE post_tag (
	post_id integer REFERENCES post (id) ON DELETE CASCADE,
	tag_id integer REFERENCES tag (id),
	PRIMARY KEY (post_id, tag_id)
);

-- Events and their link table.

CREATE TABLE event (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	title text NOT NULL,
	summary text NOT NULL,
	description text NOT NULL,
	start_at timestamptz NOT NULL,
	end_at timestamptz NOT NULL,
	cost_eur numeric(8, 2) NOT NULL,
	status text NOT NULL CHECK (status IN ('scheduled', 'cancelled')),
	is_online boolean NOT NULL,
	-- NULL for online events, which have no venue.
	venue_id integer REFERENCES venue (id),
	category_id integer NOT NULL REFERENCES event_category (id),
	organiser_id integer NOT NULL REFERENCES person (id)
);

CREATE TABLE event_speaker (
	event_id integer REFERENCES event (id) ON DELETE CASCADE,
	person_id integer REFERENCES person (id),
	PRIMARY KEY (event_id, person_id)
);
